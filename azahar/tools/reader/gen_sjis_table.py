"""Generate the reader's sjis_table.inc (shared/reader/core at the repository's top): CP932 double-byte codes -> BMP code points.

The table is indexed by (lead_index * 189 + (trail - 0x40)), where lead bytes
0x81..0x9F map to 0..30 and 0xE0..0xFC map to 31..59. Zero means unassigned.
The mapping comes from Python's cp932 codec (Microsoft code page 932).
"""
import sys

LEADS = list(range(0x81, 0xA0)) + list(range(0xE0, 0xFD))
out = []
for lead in LEADS:
    for trail in range(0x40, 0xFD):
        cp = 0
        if trail != 0x7F:
            try:
                s = bytes([lead, trail]).decode("cp932")
                if len(s) == 1 and ord(s) <= 0xFFFF:
                    cp = ord(s)
            except UnicodeDecodeError:
                pass
        out.append(cp)

assert len(out) == 60 * 189
lines = [
    "// Generated by tools/reader/gen_sjis_table.py from the CP932 mapping. Do not edit.",
    "// 60 lead bytes (0x81-0x9F, 0xE0-0xFC) x 189 trail bytes (0x40-0xFC); 0 = unassigned.",
]
for i in range(0, len(out), 12):
    lines.append("    " + ", ".join(f"0x{v:04X}" for v in out[i : i + 12]) + ",")
dest = sys.argv[1]
with open(dest, "w") as f:
    f.write("\n".join(lines) + "\n")
print(f"{dest}: {sum(1 for v in out if v)} assigned of {len(out)}")
